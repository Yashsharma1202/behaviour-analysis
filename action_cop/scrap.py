def summarise():
    ok = [f for f, s in RUN_STATUS.items() if s["status"] == "OK"]
    empty = [f for f, s in RUN_STATUS.items() if s["status"] == "EMPTY"]
    fail = [f for f, s in RUN_STATUS.items() if s["status"] == "FAIL"]

    print("\n" + "=" * 78)
    print(f"  RUN SUMMARY — {RUN_TS}" + ("  [DRY RUN — nothing written]" if DRY_RUN else ""))
    print("=" * 78)
    print(f"  {'feed':<46} {'status':<7} {'fetched':>8} {'archive':>9}")
    print("-" * 78)
    for feed in sorted(RUN_STATUS):
        s = RUN_STATUS[feed]
        print(f"  {feed:<46} {s['status']:<7} {s['fetched']:>8} {s['archive_rows']:>9,}")
    print("-" * 78)
    print(f"  OK {len(ok)}   EMPTY {len(empty)}   FAIL {len(fail)}   of {len(RUN_STATUS)} feeds")

    if fail:
        print("\n  NEEDS ATTENTION — these did not fetch (archive untouched):")
        for f in fail:
            print(f"    ! {f}: {RUN_STATUS[f]['note']}")
    if empty:
        print("\n  EMPTY — endpoint answered but returned no rows:")
        for f in empty:
            print(f"    - {f}: {RUN_STATUS[f]['note']}")
    print("=" * 78)

    if not DRY_RUN:
        try:
            with open(STATUS_FILE, "w", encoding="utf-8") as fh:
                json.dump({"run": RUN_TS, "ok": len(ok), "empty": len(empty),
                           "fail": len(fail), "feeds": RUN_STATUS}, fh, indent=2)
            print(f"  Machine-readable status -> {STATUS_FILE}")
        except Exception as e:
            print(f"  [WARN] could not write status file: {e}")


