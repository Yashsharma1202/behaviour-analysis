def clean_dataframe(df):
    if df is None or df.empty:
        return df
    df = df.dropna(how="all", axis=1)
    for col in df.columns:
        df[col] = df[col].apply(lambda x: str(x) if isinstance(x, (dict, list)) else x)
    # NSE announcement text occasionally carries raw control characters (e.g. a
    # literal vertical-tab in a GAIL filing) that openpyxl refuses to write --
    # it raises IllegalCharacterError and the whole feed fails save_feed()
    # entirely, with 01_Dashboard_Summary and 02_Announcements hitting this
    # repeatedly. Strip them the same way openpyxl's own writer would reject
    # them, instead of losing the whole feed over one bad cell.
    for col in df.select_dtypes(include="object").columns:
        df[col] = df[col].apply(
            lambda x: ILLEGAL_CHARACTERS_RE.sub("", x) if isinstance(x, str) else x
        )
    return df


def _dedupe(df, filename):
    """De-duplicate on the feed's natural key, else on all non-volatile columns.

    The key is compared as normalised TEXT, not on raw dtypes. Excel round-trips
    change types — seq_id comes back from disk as int64 but arrives from the API
    as str — so a plain drop_duplicates() sees 12345 and "12345" as different
    records and the archive silently doubles on every run. That is what put
    107k phantom rows in 02_Announcements.
    """
    if df.empty:
        return df
    key = [c for c in DEDUPE_KEYS.get(filename, []) if c in df.columns]
    if not key:
        key = [c for c in df.columns if c not in VOLATILE_COLS]
    if not key:
        return df
    # Trailing ".0" only: Excel stores an integer id as float, so 12345 returns
    # as "12345.0" while the API sends "12345". Applied to both sides equally.
    norm = df[key].astype(str).apply(
        lambda s: s.str.strip().str.replace(r"\.0$", "", regex=True))
    return df[~norm.duplicated(keep="last")]


def save_feed(df, filename, sheet, ok, note=""):
    """Merge a fetch into the archive.

    Contract:
      ok=False -> the archive is left EXACTLY as it was. A failed fetch must
                  never be able to shrink or blank accumulated history.
      ok=True  -> append, stamp fetched_at, de-duplicate on the natural key.
    """
    feed = filename[:-5]
    filepath = os.path.join(OUTPUT_DIR, filename)

    # Read the archive ONCE. The old code called pd.read_excel twice — once to
    # count rows for the log line, once again to merge. That was tolerable on the
    # 50-name archives; on the F&O universe 01_Dashboard_Summary and
    # 02_Announcements are ~4x bigger and the duplicate read costs minutes a run.
    existing, read_err = None, None
    if os.path.exists(filepath):
        try:
            existing = clean_dataframe(pd.read_excel(filepath))
            # A feed that has only ever been empty holds a single "Message"
            # placeholder column — that is not history, so do not merge it.
            if existing is not None and "Message" in existing.columns and len(existing.columns) == 1:
                existing = pd.DataFrame()
        except Exception as e:
            read_err = f"{type(e).__name__}: {e}"
    existing_rows = 0 if existing is None else len(existing)

    if not ok:
        print(f"[FETCH-FAIL] {feed}: {note} — archive left untouched ({existing_rows} rows)")
        RUN_STATUS[feed] = {"status": "FAIL", "fetched": 0,
                            "archive_rows": existing_rows, "note": note}
        return None

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    df = clean_dataframe(df)
    fetched = 0 if df is None or df.empty else len(df)

    if fetched:
        df = df.copy()
        df["fetched_at"] = RUN_TS

    # Merge with what is already on disk.
    if read_err is not None:
        print(f"[WARN] {feed}: could not read existing archive ({read_err}) "
              f"— aborting write to avoid data loss")
        RUN_STATUS[feed] = {"status": "FAIL", "fetched": fetched,
                            "archive_rows": existing_rows,
                            "note": f"archive unreadable: {read_err}"}
        return None
    if existing is not None and not existing.empty:
        df = pd.concat([existing, df], ignore_index=True) if fetched else existing

    if df is None or df.empty:
        print(f"[EMPTY] {feed}: {note}")
        RUN_STATUS[feed] = {"status": "EMPTY", "fetched": 0,
                            "archive_rows": existing_rows, "note": note}
        return None

    before = len(df)
    df = _dedupe(df, filename)
    dropped = before - len(df)

    if len(df) > ROW_WARN_THRESHOLD:
        print(f"[WARN] {feed}: {len(df):,} rows — approaching Excel's 1,048,576 limit. "
              f"Move this feed to parquet.")

    if DRY_RUN:
        print(f"[DRY-RUN] {feed}: would write {len(df):,} rows "
              f"(+{fetched} fetched, -{dropped} dupes) — {note}")
        RUN_STATUS[feed] = {"status": "OK", "fetched": fetched,
                            "archive_rows": len(df), "note": note + " [dry-run]"}
        return None

    for attempt in range(3):
        try:
            with pd.ExcelWriter(filepath, engine="openpyxl") as writer:
                df.to_excel(writer, sheet_name=sheet[:31], index=False)
                ws = writer.sheets[sheet[:31]]
                # Size columns from the header + a sample, not every cell. The old
                # version scanned all ~2.2M cells of 02_Announcements on every run.
                sample = df.head(200)
                for i, col in enumerate(df.columns, start=1):
                    # An all-null column gives NaN here, and NaN is truthy, so
                    # `int(x or 0)` raises. Guard explicitly.
                    m = sample[col].astype(str).str.len().max()
                    width = max(len(str(col)), int(m) if pd.notna(m) else 0)
                    ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = \
                        min(max(width + 3, 12), 60)
            gained = len(df) - existing_rows
            print(f"[OK] {feed}: {len(df):,} rows in archive "
                  f"(+{gained} new, {fetched} fetched, {dropped} dupes dropped) — {note}")
            RUN_STATUS[feed] = {"status": "OK", "fetched": fetched,
                                "archive_rows": len(df), "new": gained, "note": note}
            return filepath
        except PermissionError:
            time.sleep(1.5)
            if attempt == 2:
                print(f"[FILE-LOCK] {feed}: file is open in Excel — NOT saved")
                RUN_STATUS[feed] = {"status": "FAIL", "fetched": fetched,
                                    "archive_rows": existing_rows,
                                    "note": "file locked (open in Excel?)"}
        except Exception as e:
            print(f"[WRITE-FAIL] {feed}: {type(e).__name__}: {e}")
            RUN_STATUS[feed] = {"status": "FAIL", "fetched": fetched,
                                "archive_rows": existing_rows, "note": str(e)}
            break
    return None


