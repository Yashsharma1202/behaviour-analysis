def harvest(url, *, universe_set=None, params=None):
    """Single-call, market-wide feed -> (DataFrame, ok, note).

    `universe_set` narrows a market-wide response to the symbols we scrape. It
    is matched case-insensitively on a stripped symbol — NSE returns the same
    ticker with stray whitespace and mixed case across endpoints, and an exact
    `.isin()` silently drops those rows.
    """
    ok, payload = fetch_json(url, params=params)
    if not ok:
        return pd.DataFrame(), False, str(payload)
    rows = normalize_rows(payload)
    if not rows:
        shape = type(payload).__name__
        keys = list(payload)[:6] if isinstance(payload, dict) else ""
        return pd.DataFrame(), True, f"no rows (payload={shape} {keys})"
    df = pd.DataFrame(rows)
    note = f"{len(df)} rows"
    if universe_set and "symbol" in df.columns:
        before = len(df)
        df = df[df["symbol"].astype(str).str.strip().str.upper().isin(universe_set)]
        note = f"{len(df)}/{before} rows after F&O universe filter"
    return df, True, note


def harvest_symbol_wise(url_template, symbols, symbol_map, key_in_resp=None,
                        delay=0.2, params_fn=None):
    """Per-symbol feed -> (DataFrame, ok, note).

    'ok' is False only if EVERY symbol failed — that means the endpoint or the
    session is broken, not that the companies have no filings.
    """
    aggregated, failures = [], 0
    for i, sym in enumerate(symbols):
        # The symbol goes into a query string, so it MUST be percent-encoded.
        # M&M and GVT&D carry a literal '&': unencoded, `symbol=M&M` parses as
        # symbol="M" plus a stray "M" param, NSE answers 200 with an empty list,
        # and the feed logs SUCCESS. M&M has been returning zero rows on every
        # per-symbol feed for this reason. Verified 2026-08-07: raw -> 0 rows,
        # encoded -> 20 rows, for both symbols.
        url = url_template.format(symbol=quote(sym, safe=""))
        params = params_fn(sym) if params_fn else None
        ok, payload = fetch_json(url, params=params, delay=delay)
        if not ok:
            failures += 1
        else:
            items = payload.get(key_in_resp) if (key_in_resp and isinstance(payload, dict)) else None
            if not isinstance(items, list):
                items = normalize_rows(payload)
            for item in items:
                if isinstance(item, dict):
                    if "symbol" not in item and "Symbol" not in item:
                        item["symbol"] = sym
                    if "company_name" not in item and "Company Name" not in item:
                        item["company_name"] = symbol_map.get(sym, sym)
                    aggregated.append(item)
        if (i + 1) % 25 == 0:
            get_session(force=True)
        time.sleep(delay)

    total = len(symbols)
    if failures == total:
        return pd.DataFrame(), False, f"all {total} symbol requests failed"
    note = f"{len(aggregated)} rows from {total - failures}/{total} symbols"
    if failures:
        note += f" ({failures} failed)"
    return (pd.DataFrame(aggregated) if aggregated else pd.DataFrame()), True, note


