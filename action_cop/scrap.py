def get_session(force=False):
    """Persistent NSE session, cookie-warmed. Module-level so that a re-warm
    triggered deep inside a fetch actually survives for later calls (the old
    code rebound a local name and threw the new session away)."""
    global _SESSION
    if _SESSION is None or force:
        s = requests.Session()
        try:
            s.get("https://www.nseindia.com", headers=HEADERS, timeout=10)
            time.sleep(1)
            s.get("https://www.nseindia.com/companies-listing/corporate-filings-announcements",
                  headers=HEADERS, timeout=10)
            time.sleep(1)
        except Exception as e:
            print(f"[WARN] session init: {type(e).__name__}: {e}")
        _SESSION = s
    return _SESSION


def fetch_json(url, params=None, retries=3, delay=0.4):
    """Fetch JSON from NSE.

    Returns (ok: bool, payload_or_error). The bool is the whole point — the old
    version returned None for 'request failed', 'body was not JSON' and 'NSE
    said nothing', which is why 14 feeds died silently.
    """
    last = "no attempt made"
    for attempt in range(retries):
        session = get_session()
        try:
            resp = session.get(url, headers=HEADERS, params=params, timeout=15)
            if resp.status_code == 200:
                try:
                    return True, resp.json()
                except ValueError:
                    last = f"HTTP 200 but body was not JSON ({len(resp.content)} bytes)"
            elif resp.status_code in (401, 403):
                last = f"HTTP {resp.status_code} (session expired)"
                get_session(force=True)
            else:
                last = f"HTTP {resp.status_code}"
        except Exception as e:
            last = f"{type(e).__name__}: {e}"
        time.sleep(delay * (attempt + 1))
    return False, last


def normalize_rows(payload):
    """NSE hands back a bare list, {'data': [...]}, {'rows': [...]} or a single
    dict depending on the endpoint — and changes shape between releases.
    Accept all of them and always return a list of dicts."""
    if payload is None:
        return []
    if isinstance(payload, list):
        return [r for r in payload if isinstance(r, dict)]
    if isinstance(payload, dict):
        for key in ("data", "rows", "records", "result", "value", "list"):
            v = payload.get(key)
            if isinstance(v, list):
                return [r for r in v if isinstance(r, dict)]
        # A flat dict of scalars is itself a single record.
        if payload and all(not isinstance(v, (dict, list)) for v in payload.values()):
            return [payload]
    return []


