    # -- 16. Insider trading (PIT) --------------------------------------------
    # Was returning nothing for months. The endpoint answers {"acqNameList": [],
    # "data": []} with no date window — the old code read that as "no records"
    # and logged SUCCESS. Probed 2026-07-27: a rolling ONE-YEAR window returns
    # 10,601 rows. Kept MARKET-WIDE (not universe-filtered) on purpose: insider
    # disclosures are most informative in mid/small caps, and it is one call.
    step(16, "Insider Trading (PIT) — rolling 1-year window, market-wide")
    today = datetime.now()
    df, ok, note = harvest(f"{API}/corporates-pit", params={
        "index": "equities",
        "from_date": today.replace(year=today.year - 1).strftime("%d-%m-%Y"),
        "to_date": today.strftime("%d-%m-%Y"),
    })
    save_feed(df, "16_Insider_Trading_PIT.xlsx", "Insider Trading", ok, note)

    # -- 17. Insider trading plan ---------------------------------------------
    step(17, "Insider Trading Plan")
    df, ok, note = harvest(f"{API}/corporate-shareholding-disclosure", params={
        "type": "reg5",
        "from_date": today.replace(year=today.year - 1).strftime("%d-%m-%Y"),
        "to_date": today.strftime("%d-%m-%Y"),
    })
    save_feed(df, "17_Insider_Trading_Plan.xlsx", "Insider Trading Plan", ok, note)

    # -- 18. Investor complaints ----------------------------------------------
    step(18, "Investor Complaints")
