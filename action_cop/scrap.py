"""
scrap.py
===============================================================================
NSE CORPORATE DISCLOSURES SCRAPER  —  NSE F&O universe, append-only archive.

Runs twice daily from Task Scheduler (run_daily_scraper.bat) and grows an
archive of 38 NSE disclosure feeds under output_excels/.

WHAT CHANGED (2026-08-07 — universe widened to the F&O list)
------------------------------------------------------------
The universe was the Nifty 50. It is now the ~208 derivatives-eligible NSE
underlyings in fno_derivatives_list.csv (regenerate with build_universe_csv.py).

Rationale: the straddle terminal can only express an event as a trade on a name
that HAS an option chain. An earnings date on a non-F&O stock is unactionable;
the other 158 F&O names were being dropped even though they are exactly the
universe the dashboard charts.

Consequences, so they are not a surprise:
  * ~4x the HTTP round-trips (~2,300 vs ~550). Expect a materially longer run.
  * The two big feeds scale with the universe. On the 50-name run they held
    01_Dashboard_Summary 94,757 rows and 02_Announcements 78,841; at 208 names
    they land near 395k and 330k. Both fit under Excel's 1,048,576-row ceiling
    today, but ROW_WARN_THRESHOLD will start firing as they accumulate — that
    warning is the signal to move those two feeds to parquet.
  * Market-wide feeds (12, 20, 25, 26, 27, 30, 31, 37) filter against the
    universe set, so they widen automatically.
  * ISIN is blank for the 158 new names — only 08_Company_Directory's offline
    fallback reads it, and it tolerates blanks. Nothing else uses ISIN.

PRIOR PASS (2026-07-27 hardening)
---------------------------------
 1. FAILURE IS NOW VISIBLE.  Previously a network failure, a response-shape
    mismatch and a genuinely-empty feed all collapsed into `pd.DataFrame()`
    and every one of them logged [SUCCESS].  14 of 38 feeds were dead and the
    log said 0 errors.  Each feed now reports OK / EMPTY / FAIL separately,
    and the run ends with a summary table + machine-readable _run_status.json.

 2. A FAILED FETCH NEVER TOUCHES THE ARCHIVE.  Before, a bad response wrote an
    empty frame over accumulated history.  save_feed() now refuses to write
    unless the fetch actually succeeded.

 3. RESPONSE SHAPES ARE NORMALISED.  NSE returns bare lists, {"data": [...]},
    {"rows": [...]} and single dicts depending on the endpoint, and changes
    them over time.  normalize_rows() accepts all of them, so a shape change
    no longer silently empties a feed.

 4. DEDUPE KEYS PER FEED.  Only 4 of 39 saves passed a dedupe key; the rest
    de-duplicated on ALL columns, which fails the moment a volatile field
    (difference / fileSize / sysTime) drifts between fetches.  That put
    107,135 duplicate rows into 02_Announcements (58% of the file).
    DEDUPE_KEYS now assigns a natural key to every feed, and the all-column
    fallback ignores known-volatile columns.

 5. POINT-IN-TIME.  Every row is stamped `fetched_at` — what we knew, when.
    (Excluded from dedupe, or every row would look new on every run.)

 6. 13_Financial_Results was truncated to 2007-2012 because the endpoint was
    called without a period window.  Now fetched per financial year.

 7. 36_Concall only scanned symbols[:15] — 70% of the Nifty 50 was skipped.
    It is now derived from the announcements already fetched (all 50 symbols,
    and 15 fewer HTTP round-trips).

RUN
    python scrap.py                 # full run
    python scrap.py --dry-run       # fetch + report, write nothing
===============================================================================
"""

