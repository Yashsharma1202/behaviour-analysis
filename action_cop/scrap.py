    # -- 13. Financial results ------------------------------------------------
    # The old call passed no `period`, and NSE answered with a stale default
    # slice: 6 rows spanning 2005-2010 for RELIANCE, which is why the archive
    # was stuck at 2007-2012. Probed against the live API 2026-07-27:
    #     no params        ->   6 rows, Sep-2005 .. Sep-2010
    #     period=Quarterly -> 130 rows, Jun-2005 .. Mar-2024   <-- use this
    #     period=Annual    ->  39 rows, Mar-2005 .. Mar-2024
    # Adding from_date/to_date actually NARROWS the result (122 rows), so the
    # bare period parameter is what we want.
    step(13, "Financial Results (Quarterly + Annual, per symbol)")
    fr_frames, fr_fail = [], 0
    for i, sym in enumerate(symbols):
        got_any = False
        for period in ("Quarterly", "Annual"):
            ok, payload = fetch_json(
                f"{API}/corporates-financial-results",
                params={"index": "equities", "symbol": sym, "period": period},
                retries=2, delay=0.3)
            if ok:
                rows = normalize_rows(payload)
                if rows:
                    got_any = True
                    for r in rows:
                        r.setdefault("symbol", sym)
                        r.setdefault("company_name", symbol_map.get(sym, sym))
                        r.setdefault("resultPeriod", period)
                    fr_frames.append(pd.DataFrame(rows))
            time.sleep(0.2)
        if not got_any:
            fr_fail += 1
        if (i + 1) % 25 == 0:
            get_session(force=True)
    if fr_frames:
        df = pd.concat(fr_frames, ignore_index=True)
        save_feed(df, "13_Financial_Results.xlsx", "Financial Results", True,
                  f"{len(df)} rows from {len(symbols) - fr_fail}/{len(symbols)} symbols")
